def story_island_building_type(category_id: str, level: int) -> str:
    """返回指定分类与等级（1–10）的建筑显示名。"""
    buildings = STORY_ISLAND_BUILDINGS_BY_CATEGORY.get(category_id)
    if not buildings:
        buildings = STORY_ISLAND_BUILDING_FALLBACK
    index = max(1, min(10, level)) - 1
    return buildings[index]
